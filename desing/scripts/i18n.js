const MONTHS_ES = ['Ene', 'Feb', 'Mar', 'Abr', 'May', 'Jun', 'Jul', 'Ago', 'Sep', 'Oct', 'Nov', 'Dic'];
const MONTHS_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

function readStoredLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED.includes(saved)) return saved;
  } catch (_) {}
  return DEFAULT_LANGUAGE;
}

let currentLanguage = readStoredLanguage();

export function getLanguage() {
  return currentLanguage;
}

export function getLocale() {
  return LOCALES[currentLanguage];
}

export function t(key, vars = {}) {
  const text = DICTIONARIES[currentLanguage]?.[key] ?? DICTIONARIES[DEFAULT_LANGUAGE][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? String(vars[name]) : match));
}

/** Fecha corta del evento: "26 de Sep 01:22 hrs" (es), "Sep 26 01:22" (en), "9/26 01:22" (ja). */
export function formatEventDate(date) {
  const pad = (n) => String(n).padStart(2, '0');
  const hm = `${pad(date.getHours())}:${pad(date.getMinutes())}`;
  if (currentLanguage === 'en') return `${MONTHS_EN[date.getMonth()]} ${date.getDate()} ${hm}`;
  if (currentLanguage === 'ja') return `${date.getMonth() + 1}/${date.getDate()} ${hm}`;
  return `${date.getDate()} de ${MONTHS_ES[date.getMonth()]} ${hm} hrs`;
}

export function applyTranslations(root = document) {
  if (root === document) document.title = t('app.title');
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n, el.dataset.i18nN !== undefined ? { n: el.dataset.i18nN } : {});
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  });
}

export function setLanguage(lang) {
  if (!SUPPORTED.includes(lang) || lang === currentLanguage) return;
  currentLanguage = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (_) {}
  document.documentElement.lang = LOCALES[lang].split('-')[0];
  applyTranslations(document);
  window.dispatchEvent(new CustomEvent('sismosmex:languagechange', { detail: { language: lang } }));
}

